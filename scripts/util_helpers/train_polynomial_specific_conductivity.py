rows = []
for measured, temp, expected in test_cases:
    mu = viscosity_ratio(temp)
    log_mu = math.log(mu)
    if abs(log_mu) < 1e-10:
        continue
    b = math.log(expected / measured) / log_mu
    rows.append([measured, temp, b])

df = pd.DataFrame(rows, columns=["measured", "temp", "ideal_b"])

# Normalize features
X = df[["measured", "temp"]].copy()
X["measured"] /= 100000.0
X["temp"] /= 50.0
y = df["ideal_b"]

# Polynomial regression (degree 3)
poly = PolynomialFeatures(degree=3, include_bias=False)
X_poly = poly.fit_transform(X)

model = LinearRegression()
model.fit(X_poly, y)

