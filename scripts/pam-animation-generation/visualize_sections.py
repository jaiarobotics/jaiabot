#!/usr/bin/env python3
"""
visualize_sections.py

This script scans the top-level data directory (e.g., Recording_D/) for node folders 
under the "nodes" subdirectory. For each node, it loads the inbandPower table file 
(generated by Raven) and computes absolute timestamps using the global start time 
(from the earliest WAV file in that node folder).

It then creates a figure with one row of subplots (one per node) plotting inband power 
(vs. absolute time) with grid lines and axis labels. For each node, data points that remain 
above the maximum threshold (vmax) for at least a specified alert duration (default 1.5 s) 
are marked with a star; all other points are marked with circles. All subplots share a uniform 
y-axis range (which can be optionally specified via --ymin and --ymax, otherwise determined 
from the data).

The final figure is saved as a PNG file using an auto‑generated filename that includes:
  the data directory name, normalization type, vmin, vmax, gamma, in‑band parameters (cf, bw, sl, ol),
  and the alert duration (ad). If the --save flag is not provided, the figure window is displayed.

Usage example:
  python3 visualize_sections.py --data-dir Recording_D/ --norm-type power --vmin -73 --vmax -62.69 --gamma 69 --cmap viridis --alert-duration 1.5 --ymin -75 --ymax -45 --save
"""

import os, glob, argparse, re, datetime, csv
import numpy as np
import matplotlib
matplotlib.use("Agg")
import matplotlib.pyplot as plt
import matplotlib.colors as mcolors
import matplotlib.gridspec as gridspec
import matplotlib.dates as mdates

def parse_wav_timestamp(filename):
    # Expected format: runXXX_YYYY-MM-dd_hh-mm-ss.wav
    pattern = r'run\d+_h\d+_f\d+_(\d{4}-\d{2}-\d{2}_\d{2}-\d{2}-\d{2})_\d+\.wav'
    match = re.search(pattern, filename)
    if not match:
        raise ValueError(f"Filename {filename} does not match expected pattern.")
    return datetime.datetime.strptime(match.group(1), "%Y-%m-%d_%H-%M-%S")

def get_global_start_time_from_node(node_dir):
    wav_files = sorted(glob.glob(os.path.join(node_dir, "*.wav")))
    if not wav_files:
        raise RuntimeError(f"No .wav files found in {node_dir} to determine global start time.")
    return parse_wav_timestamp(os.path.basename(wav_files[0]))

def read_inband_table(table_path, global_start_time):
    sections = []
    with open(table_path, 'r') as csvfile:
        reader = csv.DictReader(csvfile, delimiter='\t')
        for row in reader:
            begin = float(row["Begin Time (s)"])
            end = float(row["End Time (s)"])
            avg_sec = (begin + end) / 2.0
            row["Avg Time (s)"] = avg_sec
            try:
                power = float(row["Inband Power (dB FS)"])
            except ValueError:
                power = 0
            row["Inband Power (dB FS)"] = power
            sections.append(row)
    times = [global_start_time + datetime.timedelta(seconds=sec["Avg Time (s)"]) for sec in sections]
    powers = [sec["Inband Power (dB FS)"] for sec in sections]
    return times, powers

def load_nodes(data_dir):
    nodes_dir = os.path.join(data_dir, "nodes")
    node_folders = [os.path.join(nodes_dir, d) for d in os.listdir(nodes_dir)
                    if os.path.isdir(os.path.join(nodes_dir, d))]
    nodes_data = {}
    for node_dir in node_folders:
        try:
            global_start = get_global_start_time_from_node(node_dir)
            table_files = glob.glob(os.path.join(node_dir, "*_inbandPower.Table.1.selections.txt"))
            if not table_files:
                print(f"No inbandPower table file found in {node_dir}. Skipping.")
                continue
            table_path = table_files[0]
            times, powers = read_inband_table(table_path, global_start)
            nodes_data[os.path.basename(node_dir)] = {"times": times, "powers": powers}
            print(f"Loaded data from {node_dir}")
        except Exception as e:
            print(f"Error loading node from {node_dir}: {e}")
    return nodes_data

def get_inband_params_from_node(node_dir):
    files = glob.glob(os.path.join(node_dir, "*_inbandPower.Table.1.selections.txt"))
    if not files:
        return None
    filename = os.path.basename(files[0])
    m = re.search(r'_cf(?P<cf>\d+)_bw(?P<bw>\d+)_sl(?P<sl>[\d.]+)_ol(?P<ol>[\d.]+)_inbandPower\.Table\.1\.selections\.txt', filename)
    if m:
        return m.groupdict()
    return None

def setup_norm_and_cmap(args):
    if args.norm_type == "linear":
        norm = mcolors.Normalize(vmin=args.vmin, vmax=args.vmax)
    elif args.norm_type == "log":
        norm = mcolors.LogNorm(vmin=max(args.vmin, 1e-3), vmax=args.vmax)
    elif args.norm_type == "power":
        norm = mcolors.PowerNorm(gamma=args.gamma, vmin=args.vmin, vmax=args.vmax)
    else:
        norm = mcolors.Normalize(vmin=args.vmin, vmax=args.vmax)
    cmap = plt.get_cmap(args.cmap)
    return norm, cmap

def main():
    parser = argparse.ArgumentParser(description="Visualize inband power vs time for each node and save as a PNG image.")
    parser.add_argument("--data-dir", required=True,
                        help="Path to the top-level data directory (e.g., Recording_D/)")
    parser.add_argument("--norm-type", choices=["linear", "log", "power"], default="linear",
                        help="Normalization type for colormap (default: linear)")
    parser.add_argument("--vmin", type=float, default=-100,
                        help="Minimum inband power (dB FS)")
    parser.add_argument("--vmax", type=float, default=0,
                        help="Maximum inband power (dB FS)")
    parser.add_argument("--gamma", type=float, default=1.0,
                        help="Gamma for power normalization (if norm-type is 'power')")
    parser.add_argument("--cmap", default="viridis",
                        help="Matplotlib colormap name (default: viridis)")
    parser.add_argument("--alert-duration", type=float, default=1.5,
                        help="Minimum consecutive duration (in seconds) above vmax to mark alerts (default: 1.5)")
    parser.add_argument("--ymin", type=float, default=None, help="Optional: y-axis minimum value")
    parser.add_argument("--ymax", type=float, default=None, help="Optional: y-axis maximum value")
    parser.add_argument("--save", action="store_true", help="If provided, save the plot to a PNG file instead of displaying")
    args = parser.parse_args()

    norm, cmap = setup_norm_and_cmap(args)
    nodes_data = load_nodes(args.data_dir)
    if not nodes_data:
        print("No nodes data found.")
        return

    # Determine shared x-axis limits.
    all_times = []
    for node in nodes_data.values():
        all_times.extend(node["times"])
    global_x_min = min(all_times)
    global_x_max = max(all_times)

    # Determine overall y-axis limits from all nodes if not specified.
    all_powers = []
    for node in nodes_data.values():
        all_powers.extend(node["powers"])
    if args.ymin is None:
        global_y_min = min(all_powers)
    else:
        global_y_min = args.ymin
    if args.ymax is None:
        global_y_max = max(all_powers)
    else:
        global_y_max = args.ymax

    n_nodes = len(nodes_data)
    
    # Retrieve inband parameters from the first node.
    nodes_dir = os.path.join(args.data_dir, "nodes")
    first_node_dir = os.path.join(nodes_dir, os.listdir(nodes_dir)[0])
    inband_params = get_inband_params_from_node(first_node_dir)
    if inband_params is None:
        inband_params = {"cf": "NA", "bw": "NA", "sl": "NA", "ol": "NA"}

    # Create subplots for each node.
    fig, axs = plt.subplots(1, n_nodes, figsize=(5 * n_nodes, 7))
    if n_nodes == 1:
        axs = [axs]
    
    for ax, (node_id, data) in zip(axs, nodes_data.items()):
        times = data["times"]
        powers = data["powers"]
        # Determine indices for alert markers.
        alert_indices = []
        n = len(times)
        i = 0
        while i < n:
            if powers[i] > args.vmax:
                start_time = times[i]
                j = i
                while j < n and powers[j] > args.vmax:
                    j += 1
                if (times[j-1] - start_time).total_seconds() >= args.alert_duration:
                    alert_indices.extend(list(range(i, j)))
                i = j
            else:
                i += 1
        
        normal_indices = [i for i in range(n) if i not in alert_indices]
        
        # Plot full line.
        ax.plot(times, powers, marker="o", linestyle="-", color="black", zorder=2)
        # Plot normal points as circles.
        if normal_indices:
            times_normal = [times[i] for i in normal_indices]
            powers_normal = [powers[i] for i in normal_indices]
            colors_normal = [cmap(norm(p)) for p in powers_normal]
            ax.scatter(times_normal, powers_normal, color=colors_normal, s=50,
                       marker="o", edgecolors="black", zorder=3)
        # Plot alert points as stars.
        if alert_indices:
            times_alert = [times[i] for i in alert_indices]
            powers_alert = [powers[i] for i in alert_indices]
            alert_color = cmap(norm(args.vmax))
            ax.scatter(times_alert, powers_alert, color=[alert_color]*len(times_alert), s=80,
                       marker="*", edgecolors="orange", zorder=4)
        ax.set_title(f"Node {node_id}")
        ax.set_xlabel("Time (UTC)")
        ax.set_ylabel("Inband Power (dB FS)")
        ax.grid(True)
        ax.set_xlim(global_x_min, global_x_max)
        ax.set_ylim(global_y_min, global_y_max)
        ax.xaxis_date()
        ax.xaxis.set_major_formatter(mdates.DateFormatter('%H:%M:%S'))
        plt.setp(ax.get_xticklabels(), rotation=45, ha="right")
    
    fig.tight_layout()
    base = os.path.basename(os.path.normpath(args.data_dir))
    output_filename = f"{base}_{args.norm_type}_vmin{args.vmin}_vmax{args.vmax}_gamma{args.gamma}_cf{inband_params['cf']}_bw{inband_params['bw']}_sl{inband_params['sl']}_ol{inband_params['ol']}_ad{args.alert_duration}.png"
    
    if args.save:
        print("About to save figure …")
        plt.savefig(output_filename, dpi=300, bbox_inches='tight')
        print("Done saving!")
        print(f"Plot saved as {output_filename}")
    else:
        plt.show()

if __name__ == "__main__":
    main()
